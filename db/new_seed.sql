-- 6. Appointments use returned IDs and actual roster slots, NEVER fixed slot IDs.
-- First five visits are completed today, one for each doctor/specialty.
-- Other patients have today's scheduled visits. Everyone gets visits at +3/+7.
DO $$
DECLARE
    visit record;
    chosen_slot int;
    appointment_id int;
    created_invoice_id int;
    payable numeric(10,2);
    treatment_code int;
BEGIN
    FOR visit IN
        SELECT p.user_id AS patient_id,
               CASE p.user_id
                   WHEN 16 THEN 6 WHEN 17 THEN 7 WHEN 18 THEN 8
                   WHEN 19 THEN 9 WHEN 20 THEN 10
                   WHEN 21 THEN 7 WHEN 22 THEN 8 WHEN 23 THEN 9
                   WHEN 24 THEN 10 ELSE 8
               END AS doctor_id,
               offsets.day_offset
        FROM patient p CROSS JOIN (VALUES (0), (3), (7)) AS offsets(day_offset)
        ORDER BY offsets.day_offset, p.user_id
    LOOP
        SELECT s.slot_id INTO chosen_slot
        FROM doctor_availability_slots s
        WHERE s.doctor_id = visit.doctor_id
          AND s.date = CURRENT_DATE + visit.day_offset
          AND s.status = 'Open'
          AND NOT EXISTS (SELECT 1 FROM appointments a WHERE a.slot_id = s.slot_id)
        ORDER BY s.start_time LIMIT 1;
        IF chosen_slot IS NULL THEN
            RAISE EXCEPTION 'No roster slot for doctor % at +% days', visit.doctor_id, visit.day_offset;
        END IF;
        appointment_id := fn_book_appointment(visit.patient_id, chosen_slot,
            'Scheduled Visit'::appointment_type_enum);

        IF visit.day_offset = 0 AND visit.patient_id BETWEEN 16 AND 20 THEN
            treatment_code := CASE visit.doctor_id
                WHEN 6 THEN 5 WHEN 7 THEN 1 WHEN 8 THEN 2 WHEN 9 THEN 3 ELSE 4 END;
            created_invoice_id := fn_complete_appointment(appointment_id,
                CASE visit.patient_id
                    WHEN 16 THEN 'Routine cardiovascular assessment'
                    WHEN 17 THEN 'Routine general health assessment'
                    WHEN 18 THEN 'Routine internal medicine assessment'
                    WHEN 19 THEN 'Headache assessment'
                    ELSE 'Minor wound assessment' END,
                'Fictional viva consultation completed today. Assessment recorded; follow-up scheduled.',
                jsonb_build_array(jsonb_build_object('treatment_code', treatment_code, 'quantity', 1),
                                  jsonb_build_object('treatment_code', 6, 'quantity', 1)));
            SELECT total_amount - insurance_amount INTO payable
            FROM invoices WHERE invoices.invoice_id = created_invoice_id;
            -- Fully paid, fully insured, unpaid, and partially paid examples.
            IF visit.patient_id = 16 AND payable > 0 THEN
                PERFORM fn_record_payment(created_invoice_id, payable, 'Cash');
            ELSIF visit.patient_id = 19 AND payable > 0 THEN
                PERFORM fn_record_payment(created_invoice_id, round(payable / 2, 2), 'Card');
            ELSIF visit.patient_id = 20 AND payable > 0 THEN
                PERFORM fn_record_payment(created_invoice_id, payable, 'Card');
            END IF;
        ELSIF visit.day_offset = 3 AND visit.patient_id = 25 THEN
            PERFORM fn_cancel_appointment(appointment_id);
        ELSIF visit.day_offset = 3 AND visit.patient_id = 24 THEN
            SELECT s.slot_id INTO chosen_slot
            FROM doctor_availability_slots s
            WHERE s.doctor_id = visit.doctor_id AND s.date = CURRENT_DATE + 4
              AND s.status = 'Open'
              AND NOT EXISTS (SELECT 1 FROM appointments a WHERE a.slot_id = s.slot_id)
            ORDER BY s.start_time LIMIT 1;
            PERFORM fn_reschedule_appointment(appointment_id, chosen_slot);
        END IF;
    END LOOP;

    -- Lunch break is outside the roster; no overlapping generated slot.
    PERFORM fn_create_walk_in(8, 25, CURRENT_DATE, TIME '12:30', TIME '13:00');
END;
$$;

