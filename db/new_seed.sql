-- 9. Synchronize all owned sequences, including trigger-generated identities.
DO $$
DECLARE
    identity_col record;
    maximum_id bigint;
    sequence_name text;
BEGIN
    FOR identity_col IN
        SELECT table_name, column_name FROM information_schema.columns
        WHERE table_schema = 'public'
          AND (is_identity = 'YES' OR column_default LIKE 'nextval(%')
    LOOP
        sequence_name := pg_get_serial_sequence(
            format('public.%I', identity_col.table_name), identity_col.column_name);
        IF sequence_name IS NOT NULL THEN
            EXECUTE format('SELECT max(%I) FROM public.%I',
                identity_col.column_name, identity_col.table_name) INTO maximum_id;
            PERFORM setval(sequence_name::regclass, COALESCE(maximum_id, 1), maximum_id IS NOT NULL);
        END IF;
    END LOOP;
END;
$$;

-- Audit entries come from the real schema triggers; no invented audit history.
-- Fail atomically if essential demo counts or dates drift.
DO $$
BEGIN
    IF (SELECT count(*) FROM app_user) <> 25
       OR (SELECT count(*) FROM staff) <> 15
       OR (SELECT count(*) FROM doctor) <> 5
       OR (SELECT count(*) FROM patient) <> 10
       OR (SELECT count(*) FROM appointments) <> 31
       OR (SELECT count(*) FROM consultations) <> 5
       OR (SELECT count(*) FROM invoices) <> 5 THEN
        RAISE EXCEPTION 'Unexpected demo seed counts';
    END IF;
    IF EXISTS (SELECT 1 FROM doctor_availability_slots WHERE date < CURRENT_DATE)
       OR EXISTS (
           SELECT 1 FROM appointments a JOIN doctor_availability_slots s USING (slot_id)
           WHERE a.status = 'Completed' AND s.date <> CURRENT_DATE
       ) THEN
        RAISE EXCEPTION 'Demo appointments must be today or later; completed visits must be today';
    END IF;
END;
$$;

